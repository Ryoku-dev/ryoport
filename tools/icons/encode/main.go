// Command encode turns the extracted Material Symbols paths into Gio IconVG data.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
	"unicode"

	"golang.org/x/exp/shiny/iconvg"
	"golang.org/x/image/math/f32"
)

type manifest struct {
	Icons []icon `json:"icons"`
}

type icon struct {
	Export string `json:"export"`
	Name   string `json:"name"`
	Fill   int    `json:"fill"`
	Path   string `json:"path"`
}

var pathToken = regexp.MustCompile(`[MLHVCSQTZmlhvcsqtz]|[-+]?(?:[0-9]*\.[0-9]+|[0-9]+\.?)(?:[eE][-+]?[0-9]+)?`)

func main() {
	if len(os.Args) != 4 {
		fmt.Fprintln(os.Stderr, "usage: encode manifest.json icons_gen.go icons.go")
		os.Exit(2)
	}
	data, err := os.ReadFile(os.Args[1])
	check(err)
	var source manifest
	check(json.Unmarshal(data, &source))

	var generated strings.Builder
	generated.WriteString("// Code generated by tools/icons; DO NOT EDIT.\n\npackage icons\n\n")
	for _, entry := range source.Icons {
		encoded, err := encodePath(entry.Path)
		if err != nil {
			check(fmt.Errorf("%s: %w", entry.Name, err))
		}
		fmt.Fprintf(&generated, "var %s = mustIcon([]byte{\n", entry.Export)
		for offset := 0; offset < len(encoded); offset += 12 {
			end := min(offset+12, len(encoded))
			generated.WriteByte('\t')
			for i, value := range encoded[offset:end] {
				if i != 0 {
					generated.WriteByte(' ')
				}
				fmt.Fprintf(&generated, "0x%02x,", value)
			}
			generated.WriteByte('\n')
		}
		generated.WriteString("})\n\n")
	}
	check(writeAtomic(os.Args[2], []byte(generated.String())))
	check(writeAtomic(os.Args[3], []byte(lookupSource(source.Icons))))
}

func encodePath(path string) ([]byte, error) {
	tokens := pathToken.FindAllString(path, -1)
	var encoder iconvg.Encoder
	encoder.Reset(iconvg.Metadata{
		ViewBox: iconvg.Rectangle{Min: f32.Vec2{0, 0}, Max: f32.Vec2{24, 24}},
		Palette: iconvg.DefaultPalette,
	})

	started := false
	var command byte
	for position := 0; position < len(tokens); {
		if len(tokens[position]) == 1 && unicode.IsLetter(rune(tokens[position][0])) {
			command = tokens[position][0]
			position++
			if command == 'Z' || command == 'z' {
				continue
			}
		}
		count, ok := argumentCount(command)
		if !ok || position+count > len(tokens) {
			return nil, fmt.Errorf("invalid path near token %d", position)
		}
		var values [6]float32
		for i := range count {
			value, err := strconv.ParseFloat(tokens[position+i], 32)
			if err != nil {
				return nil, err
			}
			values[i] = float32(value)
		}
		position += count

		switch command {
		case 'M':
			if started {
				encoder.ClosePathAbsMoveTo(values[0], values[1])
			} else {
				encoder.StartPath(0, values[0], values[1])
				started = true
			}
			command = 'L'
		case 'm':
			if started {
				encoder.ClosePathRelMoveTo(values[0], values[1])
			} else {
				encoder.StartPath(0, values[0], values[1])
				started = true
			}
			command = 'l'
		case 'L':
			encoder.AbsLineTo(values[0], values[1])
		case 'l':
			encoder.RelLineTo(values[0], values[1])
		case 'H':
			encoder.AbsHLineTo(values[0])
		case 'h':
			encoder.RelHLineTo(values[0])
		case 'V':
			encoder.AbsVLineTo(values[0])
		case 'v':
			encoder.RelVLineTo(values[0])
		case 'C':
			encoder.AbsCubeTo(values[0], values[1], values[2], values[3], values[4], values[5])
		case 'c':
			encoder.RelCubeTo(values[0], values[1], values[2], values[3], values[4], values[5])
		case 'S':
			encoder.AbsSmoothCubeTo(values[0], values[1], values[2], values[3])
		case 's':
			encoder.RelSmoothCubeTo(values[0], values[1], values[2], values[3])
		case 'Q':
			encoder.AbsQuadTo(values[0], values[1], values[2], values[3])
		case 'q':
			encoder.RelQuadTo(values[0], values[1], values[2], values[3])
		case 'T':
			encoder.AbsSmoothQuadTo(values[0], values[1])
		case 't':
			encoder.RelSmoothQuadTo(values[0], values[1])
		}
	}
	if !started {
		return nil, fmt.Errorf("path contains no move")
	}
	encoder.ClosePathEndPath()
	return encoder.Bytes()
}

func argumentCount(command byte) (int, bool) {
	switch command {
	case 'M', 'm', 'L', 'l', 'T', 't':
		return 2, true
	case 'H', 'h', 'V', 'v':
		return 1, true
	case 'C', 'c':
		return 6, true
	case 'S', 's', 'Q', 'q':
		return 4, true
	default:
		return 0, false
	}
}

func lookupSource(icons []icon) string {
	var source strings.Builder
	source.WriteString("// Package icons contains Ryoport's embedded Material Symbols.\npackage icons\n\nimport \"gioui.org/widget\"\n\nfunc mustIcon(data []byte) *widget.Icon {\n\ticon, err := widget.NewIcon(data)\n\tif err != nil {\n\t\tpanic(err)\n\t}\n\treturn icon\n}\n\nfunc ByName(name string) *widget.Icon {\n\tswitch name {\n")
	for _, entry := range icons {
		name := entry.Name
		if entry.Fill != 0 {
			name += "_fill"
		}
		fmt.Fprintf(&source, "\tcase %q:\n\t\treturn %s\n", name, entry.Export)
	}
	source.WriteString("\tdefault:\n\t\treturn nil\n\t}\n}\n")
	return source.String()
}

func writeAtomic(path string, data []byte) error {
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	temporary, err := os.CreateTemp(dir, ".icons-*")
	if err != nil {
		return err
	}
	name := temporary.Name()
	defer os.Remove(name)
	if err := temporary.Chmod(0o644); err != nil {
		temporary.Close()
		return err
	}
	if _, err := temporary.Write(data); err != nil {
		temporary.Close()
		return err
	}
	if err := temporary.Close(); err != nil {
		return err
	}
	return os.Rename(name, path)
}

func check(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
